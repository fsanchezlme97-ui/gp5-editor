"use strict";
// Bundles the Heroicons (MIT, https://heroicons.com) used by the UI into
// src/ui/icons.js so the app has no runtime dependency. Run: npm run icons
const fs = require("node:fs");
const path = require("node:path");

const ICONS = {
  outline: [
    "adjustments-vertical", "archive-box-arrow-down", "arrow-down-tray", "arrow-path", "arrow-uturn-left",
    "check", "check-circle", "chevron-down", "chevron-left", "chevron-right", "cpu-chip",
    "exclamation-triangle", "folder-open", "folder-arrow-down", "information-circle", "magnifying-glass",
    "musical-note", "power", "question-mark-circle", "globe-alt", "computer-desktop", "sparkles", "signal", "signal-slash", "x-circle", "x-mark", "bolt",
  ],
};
const root = path.join(__dirname, "..", "node_modules", "heroicons", "24");
const out = {};
for (const [style, names] of Object.entries(ICONS)) {
  for (const name of names) {
    const svg = fs.readFileSync(path.join(root, style, `${name}.svg`), "utf8");
    // keep only the inner shapes; the wrapper is rebuilt by Icons.svg()
    out[name] = svg.replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "").replace(/\s*\n\s*/g, "").trim();
  }
}
const js = `"use strict";
// Generated by scripts/build_icons.js from Heroicons v2 (MIT, Tailwind Labs). Do not edit.
(() => {
  const P = ${JSON.stringify(out, null, 2)};
  // Icons.svg("arrow-path", "cls") -> inline <svg> string (outline, 24px grid, currentColor)
  const svg = (name, cls = "") =>
    \`<svg class="ico \${cls}" xmlns="http://www.w3.org/2000/svg" fill="none" viewBox="0 0 24 24" stroke-width="1.5" stroke="currentColor" aria-hidden="true">\${P[name] || ""}</svg>\`;
  // <i data-icon="name"></i> placeholders in the HTML become inline SVGs.
  const hydrate = (root = document) => {
    root.querySelectorAll("i[data-icon]").forEach((el) => { el.outerHTML = svg(el.dataset.icon, el.className); });
  };
  window.Icons = { svg, hydrate, names: Object.keys(P) };
})();
`;
fs.mkdirSync(path.join(__dirname, "..", "src", "ui"), { recursive: true });
fs.writeFileSync(path.join(__dirname, "..", "src", "ui", "icons.js"), js);
console.log(`icons.js: ${Object.keys(out).length} icons`);
